/**
 * Word-wrap text using measured widths, so wrapping is always correct
 * regardless of which font is active when splitting happens.
 */
function wrapCommentText(doc: jsPDF, text: string, fontSize: number): string[] {
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(fontSize);
  const pageWidth = doc.internal.pageSize.getWidth();
  const maxWidth = Math.min(165, Math.max(60, pageWidth - 18 - 14));
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let currentLine = '';
  for (const word of words) {
    if (!word) continue;
    const testLine = currentLine ? `${currentLine} ${word}` : word;
    if (doc.getTextWidth(testLine) <= maxWidth || !currentLine) currentLine = testLine;
    else {
      lines.push(currentLine);
      currentLine = word;
    }
  }
  if (currentLine) lines.push(currentLine);
  return lines.length > 0 ? lines : ['No class teacher comment provided.'];
}

function commentLineHeight(fontSize: number): number {
  return COMPACT_MODE ? fontSize * 0.55 + 0.6 : fontSize * 0.62 + 0.8;
}

function commentHeightAtFont(lineCount: number, fontSize: number): number {
  return 7 + lineCount * commentLineHeight(fontSize) + 3;
}

export interface DrawAICommentOptions {
  /** Bottom edge reserved before drawing signatures/QR/calendar. */
  bottomY?: number;
  /** Minimum fit font for arbitrary long input. */
  minFontSize?: number;
  /** Explicit maximum wrapped lines for the bounded one-page policy. */
  maxLines?: number;
}

/**
 * Conservative preflight for optional trend/achievement blocks. The comment
 * is measured at its normal compact size, so a block is omitted before the
 * required comment needs to be reduced. The actual renderer may fit the
 * comment smaller, but never draws into the reserved signature zone.
 */
export function canFitReportCardOptionalSection(
  doc: jsPDF,
  startY: number,
  optionalHeight: number,
  comment: string,
  schoolInfo?: SchoolInfo,
  qrOptions: ReportCardQrOptions = {},
): boolean {
  const baseFontSize = pdfFontSize(doc, COMPACT_MODE ? 7 : 7.5);
  const lines = wrapCommentText(doc, (comment || 'No class teacher comment provided.').trim(), baseFontSize);
  const commentBottomY = getReportCardCommentBottomY(doc, schoolInfo, qrOptions);
  return startY + optionalHeight + REPORT_CARD_COMMENT_GAP + commentHeightAtFont(lines.length, baseFontSize) <= commentBottomY;
}

export function drawAIComment(
  doc: jsPDF,
  comment: string,
  startY: number,
  options: DrawAICommentOptions = {},
): number {
  const baseFontSize = pdfFontSize(doc, COMPACT_MODE ? 7 : 7.5);
  const minFontSize = Math.min(baseFontSize, options.minFontSize ?? REPORT_CARD_COMMENT_MIN_FONT_SIZE);
  const commentText = (comment || 'No class teacher comment provided.').trim();
  const initialLines = wrapCommentText(doc, commentText, baseFontSize);
  const bottomY = options.bottomY ?? doc.internal.pageSize.getHeight() - REPORT_CONTENT_BOTTOM_MARGIN;
  const availableHeight = Math.max(1, bottomY - startY);
  const headerHeight = 7;
  const contentHeight = Math.max(1, availableHeight - headerHeight - 3);
  const fittedFontSize = Math.max(
    minFontSize,
    Math.min(baseFontSize, (contentHeight / Math.max(1, initialLines.length) - 0.6) / (COMPACT_MODE ? 0.55 : 0.62)),
  );
  const lineHeight = commentLineHeight(fittedFontSize);
  const maxLinesFromHeight = Math.max(1, Math.floor(contentHeight / lineHeight));
  const maxLines = Math.min(options.maxLines ?? REPORT_CARD_COMMENT_MAX_LINES, maxLinesFromHeight);
  // The normal generated comments fit in full. Only genuinely unbounded
  // input reaches this explicit line cap; clipping is preferable to placing
  // text under the QR/signature zone or creating a second page.
  const visibleLines = initialLines.length <= maxLines ? initialLines : initialLines.slice(0, maxLines);
  const boxHeight = Math.min(availableHeight, commentHeightAtFont(visibleLines.length, fittedFontSize));

  doc.setDrawColor(100, 120, 180);
  doc.setLineWidth(0.5);
  doc.setFillColor(232, 234, 246);
  doc.rect(14, startY, 182, boxHeight, 'FD');
  doc.setFontSize(pdfFontSize(doc, 7.5));
  doc.setFont('helvetica', 'bold');
  doc.setTextColor(26, 35, 126);
  doc.text("Class Teacher's Comment:", 18, startY + 4);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(fittedFontSize);
  doc.setTextColor(0, 0, 0);
  visibleLines.forEach((line, index) => doc.text(line, 18, startY + 7 + index * lineHeight));
  return startY + boxHeight + 1;
}
