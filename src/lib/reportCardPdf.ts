// ── Draw Results Table ───────────────────────────────────────────────────────
export function drawResultsTable(
  doc: jsPDF,
  results: any[],
  classData: any,
  startY: number,
  options: ReportCardTableOptions = {}
): number {
  startY = ensureReportCardSpace(doc, startY, 24);
  const sorted = sortResultsBySubject(results);
  const isPrimary = getSchoolLevelBand(classData) === 'primary';
  const is844 = is844Curriculum(classData);
  const sevenSubjectRanking = usesSevenSubjectRanking(classData);
  const pointsMax = gradePointsMaxForClass(classData);
  const showStream = options.showStreamPosition === true;
  const showDeviation = options.showDeviation !== false;
  const assessmentColumns = options.assessmentColumns || [];
  const deviationHead = showDeviation ? ['Deviation (%)'] : [];
  const assessmentCellCount = assessmentColumns.length * 3;
  const areaLabel = is844 ? 'Subject' : 'Learning Area';
  const levelLabel = is844 ? 'Grade' : 'Performance Level';
  const tableHead = assessmentColumns.length
    ? ['No.', areaLabel, ...assessmentColumns.flatMap(column => [`${column.label}\nMarks`, `${column.label}\nPts`, `${column.label}\n${is844 ? 'Grade' : 'Level'}`]), 'Average (%)', ...deviationHead, ...(pointsMax > 0 ? [`Points (Out of ${pointsMax})`] : []), levelLabel, ...(showStream ? ['Stream Position'] : []), 'Class Position', "Teacher's Name", "Teacher's Comment"]
    : ['No.', areaLabel, 'Marks (/100)', ...deviationHead, ...(pointsMax > 0 ? [`Points (Out of ${pointsMax})`] : []), levelLabel, ...(showStream ? ['Stream Position'] : []), 'Class Position', "Teacher's Name", "Teacher's Comment"];
  const tableBody = sorted.map((r, i) => {
    const excluded = isExcludedResult(r);
    const pct = excluded ? 0 : getPercentage(r);
    const grading = excluded ? null : gradeFromPercentage(pct, classData);
    const subjectName = r.subjects?.name === 'Creative Arts' ? 'C-Arts' : (r.subjects?.name || 'N/A');
    const previous = r.previousPercentage === null || r.previousPercentage === undefined ? null : Number(r.previousPercentage);
    const deviation = excluded || previous === null ? '—' : `${pct - previous >= 0 ? '+' : ''}${(pct - previous).toFixed(1)}%`;
    const position = r.classPosition ? `${r.classPosition}/${r.classTotal || '—'}` : '—';
    const streamPosition = r.streamPosition ? `${r.streamPosition}/${r.streamTotal || '—'}` : '—';
    const row: any[] = [i + 1, subjectName];
    if (assessmentColumns.length) {
      assessmentColumns.forEach((column) => {
        const value = r.assessmentValues?.[column.id];
        if (value == null) {
          row.push('—', '—', '—');
          return;
        }
        const metric = typeof value === 'object'
          ? value
          : { marks: Number(value), outOf: 100, percentage: Number(value) };
        const examGrade = calculateGradeForClass(Number(metric.percentage), classData);
        const examLevel = 'subLevel' in examGrade ? examGrade.subLevel : examGrade.grade;
        const marksLabel = Number(metric.outOf) === 100
          ? Number(metric.marks).toFixed(0)
          : `${Number(metric.marks).toFixed(0)}/${Number(metric.outOf).toFixed(0)}`;
        row.push(marksLabel, pointsMax > 0 ? (examGrade.points ?? '—') : '—', examLevel || '—');
      });
      row.push(excluded ? 'X' : `${pct.toFixed(0)}%`);
      if (showDeviation) row.push(deviation);
    } else {
      row.push(excluded ? 'X' : `${pct.toFixed(0)}/100`);
      if (showDeviation) row.push(deviation);
    }
    if (pointsMax > 0) row.push(grading?.points ?? '—');
    row.push(excluded ? 'X' : grading?.grade || '—');
    if (showStream) row.push(streamPosition);
    row.push(position, r.teacherName || '—', r.teacherComment || '—');
    return row;
  });
  const includedRows = sorted.filter((row) => !isExcludedResult(row));
  const totalMarks = options.rankingDetails?.totalMarks ?? includedRows.reduce((sum, row) => sum + getPercentage(row), 0);
  const totalMarksLabel = `${Math.round(totalMarks)} / ${sevenSubjectRanking ? 700 : includedRows.length * 100}`;
  const totalPoints = options.rankingDetails?.totalPoints ?? includedRows.reduce((sum, row) => sum + (Number(gradeFromPercentage(getPercentage(row), classData).points) || 0), 0);
  const totalMarksRow = new Array(tableHead.length).fill('');
  const averageIndex = 2 + assessmentCellCount;
  totalMarksRow[1] = 'TOTAL MARKS'; totalMarksRow[assessmentColumns.length ? averageIndex : 2] = totalMarksLabel;
  tableBody.push(totalMarksRow);
  if (pointsMax > 0) {
    const totalPointsRow = new Array(tableHead.length).fill('');
    totalPointsRow[1] = 'TOTAL POINTS'; totalPointsRow[assessmentColumns.length ? averageIndex + 1 + (showDeviation ? 1 : 0) : 3 + (showDeviation ? 1 : 0)] = `${totalPoints || '—'} / ${sevenSubjectRanking ? 56 : includedRows.length * pointsMax}`;
    tableBody.push(totalPointsRow);
  }
  doc.setFillColor(228, 246, 225); doc.setDrawColor(137, 185, 142);
  doc.rect(9, startY - 6.5, 192, 6.5, 'FD');
  doc.setFont('helvetica', 'bold'); doc.setFontSize(pdfFontSize(doc, 8)); doc.setTextColor(26, 75, 92);
  doc.text('Learning Area Performance', 11, startY - 2.1);
  const combinedColumnStyles: Record<number, any> = {};
  if (assessmentColumns.length) {
    combinedColumnStyles[0] = { cellWidth: 7 };
    combinedColumnStyles[1] = { cellWidth: 23, fontStyle: 'bold', halign: 'left' };
    const metricWidth = Math.max(5, Math.min(10, 62 / assessmentCellCount));
    for (let index = 0; index < assessmentCellCount; index += 1) combinedColumnStyles[index + 2] = { cellWidth: metricWidth };
    let nextIndex = averageIndex;
    combinedColumnStyles[nextIndex] = { cellWidth: 10 }; nextIndex += 1;
    if (showDeviation) { combinedColumnStyles[nextIndex] = { cellWidth: 9 }; nextIndex += 1; }
    if (!isPrimary) { combinedColumnStyles[nextIndex] = { cellWidth: 9 }; nextIndex += 1; }
    combinedColumnStyles[nextIndex] = { cellWidth: 11 }; nextIndex += 1;
    if (showStream) { combinedColumnStyles[nextIndex] = { cellWidth: 10 }; nextIndex += 1; }
    combinedColumnStyles[nextIndex] = { cellWidth: 10 }; nextIndex += 1;
    combinedColumnStyles[nextIndex] = { cellWidth: 14, halign: 'left' }; nextIndex += 1;
    const assignedWidth = Object.values(combinedColumnStyles).reduce((sum: number, style: any) => sum + Number(style.cellWidth || 0), 0);
    combinedColumnStyles[nextIndex] = { cellWidth: Math.max(20, 192 - assignedWidth), halign: 'left' };
  }
  autoTable(doc, {
    startY,
    head: [tableHead],
    body: tableBody,
    pageBreak: COMPACT_MODE ? 'avoid' : 'auto',
    rowPageBreak: 'avoid',
    styles: { fontSize: pdfFontSize(doc, COMPACT_MODE ? 5.2 : 6.8), cellPadding: COMPACT_MODE ? 0.45 : 1, overflow: 'linebreak', valign: 'middle', halign: 'center' },
    headStyles: { fillColor: [223, 242, 216], textColor: [26, 35, 126], fontSize: pdfFontSize(doc, COMPACT_MODE ? 5.3 : 7), cellPadding: 0.55, halign: 'center' },
    alternateRowStyles: { fillColor: [244, 250, 239] }, margin: { left: 9, right: 9 },
    tableLineColor: [74, 112, 117], tableLineWidth: 0.45,
    columnStyles: assessmentColumns.length
      ? combinedColumnStyles
      : isPrimary
      ? (showStream
        ? { 0: { cellWidth: 7 }, 1: { cellWidth: 24, fontStyle: 'bold', halign: 'left' }, 2: { cellWidth: 16 }, ...(showDeviation ? { 3: { cellWidth: 15 } } : {}), 4: { cellWidth: 17 }, 5: { cellWidth: 15 }, 6: { cellWidth: 15 }, 7: { cellWidth: 21, halign: 'left' }, 8: { cellWidth: 62, halign: 'left' } }
        : { 0: { cellWidth: 7 }, 1: { cellWidth: 25, fontStyle: 'bold', halign: 'left' }, 2: { cellWidth: 18 }, ...(showDeviation ? { 3: { cellWidth: 16 } } : {}), 4: { cellWidth: 17 }, 5: { cellWidth: 16 }, 6: { cellWidth: 22, halign: 'left' }, 7: { cellWidth: 71, halign: 'left' } })
      : (showStream
        ? { 0: { cellWidth: 7 }, 1: { cellWidth: 22, fontStyle: 'bold', halign: 'left' }, 2: { cellWidth: 15 }, ...(showDeviation ? { 3: { cellWidth: 14 } } : {}), 4: { cellWidth: 13 }, 5: { cellWidth: 16 }, 6: { cellWidth: 15 }, 7: { cellWidth: 15, halign: 'left' }, 8: { cellWidth: 20 }, 9: { cellWidth: 55, halign: 'left' } }
        : { 0: { cellWidth: 7 }, 1: { cellWidth: 23, fontStyle: 'bold', halign: 'left' }, 2: { cellWidth: 17 }, ...(showDeviation ? { 3: { cellWidth: 16 } } : {}), 4: { cellWidth: 15 }, 5: { cellWidth: 17 }, 6: { cellWidth: 15, halign: 'left' }, 7: { cellWidth: 22 }, 8: { cellWidth: 60, halign: 'left' } }),
    didParseCell: (data: any) => {
      const teacherIndex = tableHead.indexOf("Teacher's Name");
      if (data.column.index === teacherIndex) data.cell.styles.halign = 'left';
      if (data.section !== 'body') return;
      const value = String(data.cell.raw ?? '');
      const deviationIndex = tableHead.indexOf('Deviation (%)');
      if (data.column.index === deviationIndex && value !== '—') {
        data.cell.styles.textColor = value.startsWith('+') ? [22, 128, 65] : value.startsWith('-') ? [190, 45, 45] : [100, 100, 100];
        data.cell.styles.fontStyle = 'bold';
      }
    },
    didDrawCell: (data: any) => {
      if (data.section === 'body') {
        doc.setDrawColor(95, 125, 130);
        doc.setLineWidth(0.28);
        doc.line(data.cell.x, data.cell.y + data.cell.height, data.cell.x + data.cell.width, data.cell.y + data.cell.height);
      }
    },
  });
  return (doc as any).lastAutoTable.finalY;
}

