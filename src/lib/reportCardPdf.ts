export interface ReportCardSignatureLayout {
  hasQr: boolean;
  coreHeight: number;
  calendarNoticeLines: string[];
  totalHeight: number;
}

function reportCardCalendarNoticeLines(schoolInfo?: SchoolInfo): string[] {
  const closingDate = schoolInfo?.school_closes_on
    ? new Date(`${schoolInfo.school_closes_on}T00:00:00`).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
    : '';
  const openingDate = schoolInfo?.school_opens_on
    ? new Date(`${schoolInfo.school_opens_on}T00:00:00`).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
    : schoolInfo?.next_term_start_date
      ? new Date(`${schoolInfo.next_term_start_date}T00:00:00`).toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })
      : '';
  return [
    closingDate ? `School closes on: ${closingDate}` : '',
    openingDate ? `School opens on: ${openingDate}` : '',
  ].filter(Boolean);
}

export function getReportCardSignatureLayout(
  schoolInfo?: SchoolInfo,
  qrOptions: ReportCardQrOptions = {},
): ReportCardSignatureLayout {
  const hasQr = Boolean(qrOptions.loginUrl || qrOptions.assessmentNumber || typeof window !== 'undefined');
  const coreHeight = COMPACT_MODE ? (hasQr ? 38 : 14) : (hasQr ? 52 : 34);
  const calendarNoticeLines = reportCardCalendarNoticeLines(schoolInfo);
  return {
    hasQr,
    coreHeight,
    calendarNoticeLines,
    totalHeight: coreHeight + (calendarNoticeLines.length > 0 ? (COMPACT_MODE ? 12 : 15) : 5),
  };
}

/** Top of the fixed bottom signature/QR/calendar zone. */
export function getReportCardSignatureZoneTop(
  doc: jsPDF,
  schoolInfo?: SchoolInfo,
  qrOptions: ReportCardQrOptions = {},
): number {
  return doc.internal.pageSize.getHeight() - REPORT_CARD_FOOTER_GAP - getReportCardSignatureLayout(schoolInfo, qrOptions).totalHeight;
}

/** Bottom edge available to the required class-teacher comment box. */
export function getReportCardCommentBottomY(
  doc: jsPDF,
  schoolInfo?: SchoolInfo,
  qrOptions: ReportCardQrOptions = {},
): number {
  return getReportCardSignatureZoneTop(doc, schoolInfo, qrOptions) - REPORT_CARD_COMMENT_GAP;
}

